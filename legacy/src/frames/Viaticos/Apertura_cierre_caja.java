    private void eliminar_caja_abierta_de_combo() {
        String caja = "";
        rs2 = con.listar_datos("select (a.cod_caja||'-'||a.descri_caja) as caja "
                + "from caja a , cierre_apertura_caja b where a.cod_caja = b.cod_caja "
                + "and b.estado_cierre_apert = 'ACTIVO'");

        try {
            while (rs2.next()) {
                caja = rs2.getString("caja");

            }
        } catch (SQLException ex) {
            Logger.getLogger(Apertura_cierre_caja.class.getName()).log(Level.SEVERE, null, ex);
        }

        for (int i = 0; i < vcombo_caja.getItemCount(); i++) {
            if (vcombo_caja.getItemAt(i).equals(caja)) {
                vcombo_caja.removeItem(caja);
            }
        }
    }

