    private void cargar_datos_apertura() {
        if (!cod_caja.equals("")) {
            rs3 = con.listar_datos("select a.cod_cierre_apertura_caja, a.cod_emp,  apert_fecha,"
                    + "apert_hora, apert_monto , (b.cod_caja||'-'||b.descri_caja) as caja "
                    + "from cierre_apertura_caja a, caja b"
                    + " where b.cod_caja = a.cod_caja and a.cod_emp =" + acceso.obtenerEmpleado() + " "
                    + "and b.cod_caja =  " + cod_caja + " and "
                    + "estado_cierre_apert = 'ACTIVO'");
            try {
                if (rs3.isBeforeFirst()) {
                    while (rs3.next()) {
                        vapert_cierre_cod.setText(rs3.getString("cod_cierre_apertura_caja"));
                        vcombo_caja.setSelectedItem(rs3.getString("caja"));
                        vapertura_fecha.setDate(convertir_a_date(rs3.getString("apert_fecha")));
                        vapertura_monto.setText(rs3.getString("apert_monto"));
                        hora_apertura = rs3.getString("apert_hora");
                        btncierre.setEnabled(true);
                    }
                } else {
                    btnapertura.setEnabled(true);
                }
            } catch (SQLException ex) {
                Logger.getLogger(Cobro.class.getName()).log(Level.SEVERE, null, ex);
            }
            vhora_apertura.setValue(hora_apertura.substring(0, 2));
            vminuto_apertura.setValue(hora_apertura.substring(3, 5));

        } else {
            btnapertura.setEnabled(true);
        }
    }

    private void buscar_caja_abierta_del_empleado() {
        for (int i = 0; i < vcombo_caja.getItemCount(); i++) {
            rs2 = con.listar_datos("select cod_caja from cierre_apertura_caja where "
                    + "cod_emp = " + acceso.obtenerEmpleado() + " and cod_caja = "
                    + vcombo_caja.getItemAt(i).toString().substring(0, 1) + " and "
                    + "estado_cierre_apert = 'ACTIVO' ");
            try {

                while (rs2.next()) {
                    cod_caja = rs2.getString("cod_caja");
                    vcombo_caja.setSelectedIndex(i);
                }
            } catch (SQLException ex) {
                Logger.getLogger(Apertura_cierre_caja.class.getName()).log(Level.SEVERE, null, ex);
            }
        }

    }

