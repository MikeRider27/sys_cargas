CREATE INDEX emi_crt_ped_ix          ON emi_crt (id_ped);
CREATE INDEX evento_carga_crt_ix     ON evento_carga (id_crt);
CREATE INDEX reclamos_rped_ix        ON reclamos (id_rped);
CREATE INDEX asignacion_ped_ix       ON asignacion (id_ped);
CREATE INDEX asignacion_viaj_ix      ON asignacion (id_viaj);
CREATE INDEX asig_flet_viaj_ix       ON asig_flet (id_viaj);
CREATE INDEX viatico_ap_cie_ix       ON viatico (id_ap_cie);
CREATE INDEX comprobante_viat_ix     ON comprobante (id_viat);
