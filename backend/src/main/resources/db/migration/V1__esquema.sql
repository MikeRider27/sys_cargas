-- ---------------------------------------------------------------------
-- Estados (fijos, usados por la logica de negocio)
-- ---------------------------------------------------------------------
CREATE TABLE estado (
    id_est   SMALLINT    PRIMARY KEY,
    descrip  VARCHAR(40) NOT NULL UNIQUE
);

-- ---------------------------------------------------------------------
-- Empresa y seguridad
-- ---------------------------------------------------------------------
CREATE TABLE rol (
    id_rol   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo   VARCHAR(30) NOT NULL UNIQUE,
    descrip  VARCHAR(80) NOT NULL
);

CREATE TABLE sucursal (
    id_suc   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip  VARCHAR(80)  NOT NULL UNIQUE,
    direc    VARCHAR(150) NOT NULL,
    telef    VARCHAR(30)  NOT NULL,
    correo   VARCHAR(120),
    id_est   SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

CREATE TABLE cargo (
    id_car   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip  VARCHAR(80) NOT NULL UNIQUE,
    id_est   SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

-- [C05] personal ya no depende de usuario; es usuario quien apunta a personal.
CREATE TABLE personal (
    id_per     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_doc    VARCHAR(20)  NOT NULL UNIQUE,
    nombres    VARCHAR(80)  NOT NULL,
    apellidos  VARCHAR(80)  NOT NULL,
    fecha_nac  DATE,
    direcc     VARCHAR(150) NOT NULL,
    telef      VARCHAR(30)  NOT NULL,
    id_car     INTEGER  NOT NULL REFERENCES cargo,
    id_suc     INTEGER  NOT NULL REFERENCES sucursal,
    id_est     SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

-- [C04][C06] PK simple, username unico, hash BCrypt, control de intentos.
CREATE TABLE usuario (
    id_usu             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username           VARCHAR(50)  NOT NULL UNIQUE,
    password_hash      VARCHAR(100) NOT NULL,
    id_rol             INTEGER  NOT NULL REFERENCES rol,
    id_per             INTEGER  UNIQUE REFERENCES personal,
    id_est             SMALLINT NOT NULL DEFAULT 1 REFERENCES estado,
    intentos_fallidos  INTEGER  NOT NULL DEFAULT 0,
    bloqueado_hasta    TIMESTAMPTZ,
    ultimo_acceso      TIMESTAMPTZ
);

-- ---------------------------------------------------------------------
-- Geografia y referenciales generales
-- [C08] claves compuestas en cascada reemplazadas por claves simples.
-- ---------------------------------------------------------------------
CREATE TABLE pais (
    id_pais  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip  VARCHAR(80) NOT NULL UNIQUE,
    tarifa   NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (tarifa >= 0),
    id_est   SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

CREATE TABLE estad_prov (
    id_prov  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pais  INTEGER NOT NULL REFERENCES pais,
    descrip  VARCHAR(80) NOT NULL,
    id_est   SMALLINT NOT NULL DEFAULT 1 REFERENCES estado,
    UNIQUE (id_pais, descrip)
);

CREATE TABLE ciudad (
    id_ciud  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_prov  INTEGER NOT NULL REFERENCES estad_prov,
    descrip  VARCHAR(80) NOT NULL,
    id_est   SMALLINT NOT NULL DEFAULT 1 REFERENCES estado,
    UNIQUE (id_prov, descrip)
);

CREATE TABLE nacionalidad (
    id_nac   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip  VARCHAR(60) NOT NULL UNIQUE,
    id_est   SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

CREATE TABLE moneda (
    id_mon   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    abrev    VARCHAR(10) NOT NULL UNIQUE,
    descrip  VARCHAR(60) NOT NULL,
    id_est   SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

CREATE TABLE aduana (
    id_adu   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip  VARCHAR(80) NOT NULL UNIQUE,
    id_ciud  INTEGER REFERENCES ciudad,
    id_est   SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

-- [C02] extension pasa de VARCHAR ('500kmts') a numerico en km.
CREATE TABLE ruta (
    id_ruta       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip       VARCHAR(80) NOT NULL UNIQUE,
    extension_km  NUMERIC(10,2) NOT NULL CHECK (extension_km > 0),
    id_ciud       INTEGER NOT NULL REFERENCES ciudad,
    id_est        SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

-- [C01] descrip era BYTEA.
CREATE TABLE peaje (
    id_peaj  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip  VARCHAR(80) NOT NULL,
    tarifa   NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (tarifa >= 0),
    id_ruta  INTEGER REFERENCES ruta,
    id_ciud  INTEGER NOT NULL REFERENCES ciudad,
    id_est   SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

-- [C01] descrip era INTEGER.
CREATE TABLE itinerario (
    id_iti   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip  VARCHAR(80) NOT NULL UNIQUE,
    id_est   SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

-- ---------------------------------------------------------------------
-- Clientes, despachantes y mercaderias
-- ---------------------------------------------------------------------
-- [C07] id_tc colisionaba con tracto.id_tc.
CREATE TABLE tipo_doc (
    id_tdoc  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip  VARCHAR(40) NOT NULL UNIQUE
);

-- [C07] id_cli se confundia con el tipo dentro de cliente.
CREATE TABLE tipo_cli (
    id_tcli  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip  VARCHAR(40) NOT NULL UNIQUE
);

-- [C09] El nro. de documento ya no es la PK (RUC con DV, pasaportes
-- alfanumericos). Reemplaza tambien a d_cli_tdoc.
CREATE TABLE cliente (
    id_cliente  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tdoc     INTEGER NOT NULL REFERENCES tipo_doc,
    nro_doc     VARCHAR(30)  NOT NULL,
    nombres     VARCHAR(120) NOT NULL,
    apellidos   VARCHAR(80),
    fecha_nac   DATE,
    direcc      VARCHAR(150) NOT NULL,
    telef       VARCHAR(30)  NOT NULL,
    correo      VARCHAR(120),
    id_tcli     INTEGER NOT NULL REFERENCES tipo_cli,
    id_nac      INTEGER NOT NULL REFERENCES nacionalidad,
    id_est      SMALLINT NOT NULL DEFAULT 1 REFERENCES estado,
    UNIQUE (id_tdoc, nro_doc)
);

CREATE TABLE despachante (
    id_desp    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_doc    VARCHAR(20) NOT NULL UNIQUE,
    nombres    VARCHAR(80) NOT NULL,
    apellidos  VARCHAR(80) NOT NULL,
    telef      VARCHAR(30) NOT NULL,
    id_est     SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

CREATE TABLE tipo_merc (
    id_tm    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip  VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE mercaderia (
    id_merc  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip  VARCHAR(120) NOT NULL UNIQUE,
    id_tm    INTEGER NOT NULL REFERENCES tipo_merc,
    id_est   SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

CREATE TABLE tipo_carg (
    id_tic   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip  VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE tip_event (
    id_tip   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip  VARCHAR(60) NOT NULL UNIQUE
);

-- ---------------------------------------------------------------------
-- Flota
-- [C08] modelo_t y tipo_semi con PK simple.
-- ---------------------------------------------------------------------
CREATE TABLE marca_t (
    id_mt    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip  VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE modelo_t (
    id_modt  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_mt    INTEGER NOT NULL REFERENCES marca_t,
    descrip  VARCHAR(60) NOT NULL,
    anho     SMALLINT NOT NULL CHECK (anho BETWEEN 1950 AND 2100),
    UNIQUE (id_mt, descrip, anho)
);

-- [C02] tara era VARCHAR.
CREATE TABLE tracto (
    id_tc      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapa_nr   VARCHAR(15) NOT NULL UNIQUE,
    chasis_nr  VARCHAR(40) NOT NULL UNIQUE,
    tara       NUMERIC(10,2) NOT NULL CHECK (tara > 0),
    id_modt    INTEGER NOT NULL REFERENCES modelo_t,
    id_est     SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

CREATE TABLE marca_s (
    id_ms    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip  VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE tipo_semi (
    id_tsem  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip  VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE semirremolque (
    id_semi     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapa_nro   VARCHAR(15) NOT NULL UNIQUE,
    chasis_nro  VARCHAR(40) NOT NULL UNIQUE,
    cap_carg    NUMERIC(10,2) NOT NULL CHECK (cap_carg > 0),
    largo       NUMERIC(6,2)  NOT NULL CHECK (largo > 0),
    ancho       NUMERIC(6,2)  NOT NULL CHECK (ancho > 0),
    alto        NUMERIC(6,2)  NOT NULL CHECK (alto > 0),
    id_tsem     INTEGER NOT NULL REFERENCES tipo_semi,
    id_ms       INTEGER NOT NULL REFERENCES marca_s,
    id_est      SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

-- [C01] descrip era INTEGER.
CREATE TABLE accesorios (
    id_acc   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip  VARCHAR(80) NOT NULL UNIQUE,
    id_est   SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

-- [C01] direc era INTEGER.
CREATE TABLE fletero (
    id_flet    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_doc    VARCHAR(20)  NOT NULL UNIQUE,
    nombres    VARCHAR(80)  NOT NULL,
    apellidos  VARCHAR(80)  NOT NULL,
    camion     VARCHAR(80)  NOT NULL,
    telef      VARCHAR(30)  NOT NULL,
    direc      VARCHAR(150) NOT NULL,
    nro_reg    VARCHAR(30)  NOT NULL,
    id_est     SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

-- ---------------------------------------------------------------------
-- Modulo Pedidos
-- ---------------------------------------------------------------------
CREATE TABLE r_pedido (
    id_rped     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha       DATE NOT NULL DEFAULT CURRENT_DATE,
    descrip     VARCHAR(300) NOT NULL,
    id_cliente  INTEGER NOT NULL REFERENCES cliente,
    id_per      INTEGER NOT NULL REFERENCES personal,
    id_est      SMALLINT NOT NULL DEFAULT 2 REFERENCES estado
);

-- [C02][C10] importes numericos, estado, fecha y moneda.
CREATE TABLE coti_flete (
    id_cot      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha       DATE NOT NULL DEFAULT CURRENT_DATE,
    id_cliente  INTEGER NOT NULL REFERENCES cliente,
    id_pais_o   INTEGER NOT NULL REFERENCES pais,
    id_pais_d   INTEGER NOT NULL REFERENCES pais,
    peso        NUMERIC(12,2) NOT NULL CHECK (peso > 0),
    volumen     NUMERIC(12,2) NOT NULL CHECK (volumen > 0),
    costo       NUMERIC(18,2) NOT NULL CHECK (costo >= 0),
    id_mon      INTEGER  NOT NULL REFERENCES moneda,
    id_per      INTEGER  NOT NULL REFERENCES personal,
    id_est      SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

CREATE TABLE d_co_mer (
    id_cot   INTEGER NOT NULL REFERENCES coti_flete ON DELETE CASCADE,
    item     SMALLINT NOT NULL,
    id_merc  INTEGER NOT NULL REFERENCES mercaderia,
    PRIMARY KEY (id_cot, item)
);

CREATE TABLE ped_flete (
    id_ped   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha    DATE NOT NULL DEFAULT CURRENT_DATE,
    descrip  VARCHAR(300) NOT NULL,
    id_rped  INTEGER NOT NULL REFERENCES r_pedido,
    id_desp  INTEGER NOT NULL REFERENCES despachante,
    id_tic   INTEGER NOT NULL REFERENCES tipo_carg,
    id_per   INTEGER NOT NULL REFERENCES personal,
    id_est   SMALLINT NOT NULL DEFAULT 2 REFERENCES estado
);

-- [C02] cantidad era VARCHAR; [C11] PK sin id_merc (item ya identifica).
CREATE TABLE d_merc (
    id_ped    INTEGER NOT NULL REFERENCES ped_flete ON DELETE CASCADE,
    item      SMALLINT NOT NULL,
    id_merc   INTEGER NOT NULL REFERENCES mercaderia,
    cantidad  NUMERIC(12,2) NOT NULL CHECK (cantidad > 0),
    PRIMARY KEY (id_ped, item)
);

-- [C10][C12] id_est faltante (abm_crt lo usaba), vinculo al pedido de
-- flete, numeracion por anho con PK surrogate y CHECK origen<>destino.
CREATE TABLE emi_crt (
    id_crt     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro        INTEGER  NOT NULL,
    anho       SMALLINT NOT NULL,
    fecha_emi  DATE NOT NULL DEFAULT CURRENT_DATE,
    id_ped     INTEGER REFERENCES ped_flete,
    id_mon     INTEGER NOT NULL REFERENCES moneda,
    id_per     INTEGER NOT NULL REFERENCES personal,
    id_expo    INTEGER NOT NULL REFERENCES cliente,
    id_impo    INTEGER NOT NULL REFERENCES cliente,
    id_adu     INTEGER NOT NULL REFERENCES aduana,
    id_pais_o  INTEGER NOT NULL REFERENCES pais,
    id_pais_d  INTEGER NOT NULL REFERENCES pais,
    id_est     SMALLINT NOT NULL DEFAULT 1 REFERENCES estado,
    UNIQUE (nro, anho),
    CHECK (id_pais_o <> id_pais_d)
);

CREATE TABLE d_m_emi (
    id_crt    INTEGER NOT NULL REFERENCES emi_crt ON DELETE CASCADE,
    item      SMALLINT NOT NULL,
    id_merc   INTEGER NOT NULL REFERENCES mercaderia,
    cantidad  NUMERIC(12,2) NOT NULL CHECK (cantidad > 0),
    peso      NUMERIC(12,2) NOT NULL CHECK (peso > 0),
    volumen   NUMERIC(12,2) NOT NULL CHECK (volumen > 0),
    valor     NUMERIC(18,2) NOT NULL CHECK (valor >= 0),
    id_mon    INTEGER NOT NULL REFERENCES moneda,
    PRIMARY KEY (id_crt, item)
);

-- [C13] eventos + d_event fusionados: la PK de d_event no incluia item y
-- eventos permitia una sola cabecera por CRT.
CREATE TABLE evento_carga (
    id_evento   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_crt      INTEGER NOT NULL REFERENCES emi_crt,
    id_tip      INTEGER NOT NULL REFERENCES tip_event,
    fecha_hora  TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP(0),
    coment      VARCHAR(300),
    id_per      INTEGER NOT NULL REFERENCES personal,
    id_est      SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

-- [C14] datos de cierre opcionales al registrar; se elimina id_docc
-- redundante (el cliente se obtiene del pedido).
CREATE TABLE reclamos (
    id_recla  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha     DATE NOT NULL DEFAULT CURRENT_DATE,
    descrip   VARCHAR(500) NOT NULL,
    id_rped   INTEGER NOT NULL REFERENCES r_pedido,
    id_ped    INTEGER REFERENCES ped_flete,
    id_per    INTEGER NOT NULL REFERENCES personal,
    id_est    SMALLINT NOT NULL DEFAULT 2 REFERENCES estado,
    fecha_c   DATE,
    solucion  VARCHAR(500),
    avisado   BOOLEAN NOT NULL DEFAULT FALSE,
    CHECK (fecha_c IS NULL OR fecha_c >= fecha)
);

-- ---------------------------------------------------------------------
-- Modulo Logistica
-- ---------------------------------------------------------------------
CREATE TABLE r_viaje (
    id_viaj    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_sal  DATE NOT NULL,
    id_per     INTEGER NOT NULL REFERENCES personal,
    id_iti     INTEGER NOT NULL REFERENCES itinerario,
    id_adu     INTEGER NOT NULL REFERENCES aduana,
    id_ruta    INTEGER NOT NULL REFERENCES ruta,
    id_est     SMALLINT NOT NULL DEFAULT 2 REFERENCES estado
);

-- [C15] d_viaj_ciud sin el id_viat que no correspondia.
CREATE TABLE viaje_ciudad (
    id_viaj  INTEGER NOT NULL REFERENCES r_viaje ON DELETE CASCADE,
    item     SMALLINT NOT NULL,
    id_ciud  INTEGER NOT NULL REFERENCES ciudad,
    PRIMARY KEY (id_viaj, item)
);

-- [C07] iid_per -> id_per; [C16] d_asi_via reemplazada por id_viaj.
CREATE TABLE asignacion (
    id_asig    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_carg DATE NOT NULL,
    descrip    VARCHAR(300) NOT NULL,
    id_ped     INTEGER NOT NULL REFERENCES ped_flete,
    id_viaj    INTEGER REFERENCES r_viaje,
    id_cond    INTEGER NOT NULL REFERENCES personal,
    id_tc      INTEGER NOT NULL REFERENCES tracto,
    id_semi    INTEGER NOT NULL REFERENCES semirremolque,
    id_per     INTEGER NOT NULL REFERENCES personal,
    id_est     SMALLINT NOT NULL DEFAULT 2 REFERENCES estado
);

CREATE TABLE d_acc (
    id_asig  INTEGER NOT NULL REFERENCES asignacion ON DELETE CASCADE,
    item     SMALLINT NOT NULL,
    id_acc   INTEGER NOT NULL REFERENCES accesorios,
    obs      VARCHAR(150),
    PRIMARY KEY (id_asig, item)
);

CREATE TABLE asig_flet (
    id_aflet  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha     DATE NOT NULL DEFAULT CURRENT_DATE,
    id_flet   INTEGER NOT NULL REFERENCES fletero,
    id_viaj   INTEGER NOT NULL REFERENCES r_viaje,
    id_est    SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

-- [C02] kilometraje y combustible eran VARCHAR.
CREATE TABLE r_salida (
    id_salid   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_sal  DATE NOT NULL,
    kilom_sal  NUMERIC(12,1) NOT NULL CHECK (kilom_sal >= 0),
    comb_sal   NUMERIC(10,2) NOT NULL CHECK (comb_sal >= 0),
    id_asig    INTEGER NOT NULL REFERENCES asignacion,
    id_est     SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);
CREATE UNIQUE INDEX r_salida_asig_vigente_uk ON r_salida (id_asig) WHERE id_est <> 0;

CREATE TABLE r_llegada (
    id_lleg     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_lleg  DATE NOT NULL,
    kilom_lleg  NUMERIC(12,1) NOT NULL CHECK (kilom_lleg >= 0),
    comb_lleg   NUMERIC(10,2) NOT NULL CHECK (comb_lleg >= 0),
    id_salid    INTEGER NOT NULL REFERENCES r_salida,
    id_est      SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);
CREATE UNIQUE INDEX r_llegada_salid_vigente_uk ON r_llegada (id_salid) WHERE id_est <> 0;

-- ---------------------------------------------------------------------
-- Modulo Rendiciones
-- ---------------------------------------------------------------------
-- [C01] descrip era INTEGER.
CREATE TABLE caja (
    id_caj   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descrip  VARCHAR(60) NOT NULL UNIQUE,
    id_suc   INTEGER NOT NULL REFERENCES sucursal,
    id_est   SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

-- [C17] PK simple, datos de cierre opcionales, una sola apertura abierta
-- por caja.
CREATE TABLE aper_cierr_caja (
    id_ap_cie         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_caj            INTEGER NOT NULL REFERENCES caja,
    id_per            INTEGER NOT NULL REFERENCES personal,
    id_mon            INTEGER NOT NULL REFERENCES moneda,
    fecha_hora_ap     TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP(0),
    monto_inic        NUMERIC(18,2) NOT NULL CHECK (monto_inic >= 0),
    fecha_hora_cierr  TIMESTAMP,
    monto_cierr       NUMERIC(18,2) CHECK (monto_cierr >= 0),
    id_est            SMALLINT NOT NULL DEFAULT 1 REFERENCES estado,
    CHECK (fecha_hora_cierr IS NULL OR fecha_hora_cierr >= fecha_hora_ap)
);
CREATE UNIQUE INDEX aper_cierr_caja_abierta_uk ON aper_cierr_caja (id_caj) WHERE fecha_hora_cierr IS NULL AND id_est <> 0;

-- [C18] monto numerico, fecha, viaje y caja de origen (la moneda es la de
-- la apertura de caja); reemplaza d_viat_mon.
CREATE TABLE viatico (
    id_viat    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha      DATE NOT NULL DEFAULT CURRENT_DATE,
    id_per     INTEGER NOT NULL REFERENCES personal,
    id_viaj    INTEGER REFERENCES r_viaje,
    id_ap_cie  INTEGER NOT NULL REFERENCES aper_cierr_caja,
    monto      NUMERIC(18,2) NOT NULL CHECK (monto > 0),
    obs        VARCHAR(300),
    id_est     SMALLINT NOT NULL DEFAULT 2 REFERENCES estado
);

-- [C18] se elimina total (redundante con monto).
CREATE TABLE comprobante (
    id_comp   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_viat   INTEGER NOT NULL REFERENCES viatico,
    fecha     DATE NOT NULL,
    nro_comp  VARCHAR(30) NOT NULL,
    descrip   VARCHAR(200) NOT NULL,
    monto     NUMERIC(18,2) NOT NULL CHECK (monto > 0),
    id_est    SMALLINT NOT NULL DEFAULT 1 REFERENCES estado
);

-- [C18] rendicion ligada al viatico (antes aislada); reemplaza d_ren_comp.
CREATE TABLE rendiciones (
    id_rend          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_viat          INTEGER NOT NULL REFERENCES viatico,
    fecha            DATE NOT NULL DEFAULT CURRENT_DATE,
    total_asignado   NUMERIC(18,2) NOT NULL,
    total_rendido    NUMERIC(18,2) NOT NULL,
    diferencia       NUMERIC(18,2) NOT NULL,
    obs              VARCHAR(300),
    id_per           INTEGER NOT NULL REFERENCES personal,
    id_est           SMALLINT NOT NULL DEFAULT 1 REFERENCES estado,
    CHECK (diferencia = total_asignado - total_rendido)
);
CREATE UNIQUE INDEX rendiciones_viat_vigente_uk ON rendiciones (id_viat) WHERE id_est <> 0;

-- ---------------------------------------------------------------------
-- Indices para FKs usadas en busquedas frecuentes
-- ---------------------------------------------------------------------
CREATE INDEX r_pedido_cliente_ix     ON r_pedido (id_cliente);
